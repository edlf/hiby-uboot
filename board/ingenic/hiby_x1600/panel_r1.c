static void lg35583_send_init(void)
{
	int i;

	for (i = 0; i < ARRAY_SIZE(lg35583_init_seq); i++) {
		const struct lg_write *w = &lg35583_init_seq[i];

		if (!w->reg) {
			mdelay(w->val);
			continue;
		}
		spi_writecomm(w->reg);
		if (w->val >= 0)
			hiby_lcd_spi_write16(LG_DATA | w->val);
	}
}

/* VCCIO, 50 ms, CS high, VCC, then reset */
static int r1_power_on(void)
{
	if (hiby_lcd_supply(HIBY_LDO_VCCIO, 1))
		return -1;
	mdelay(50);
	gpio_set_value(HIBY_LCD_SPI_CS, 1);
	if (hiby_lcd_supply(HIBY_LDO_VCC, 1))
		return -1;
	mdelay(5);

	gpio_set_value(HIBY_LCD_RST, 1);
	mdelay(5);
	gpio_set_value(HIBY_LCD_RST, 0);
	mdelay(50);
	gpio_set_value(HIBY_LCD_RST, 1);
	mdelay(30);

	if (lcd_id)
		hiby_lcd_spi_send9(st7701s_init_seq,
				   ARRAY_SIZE(st7701s_init_seq));
	else
		lg35583_send_init();
	return 0;
}

/* Display Off, Sleep In, reset, VCC, 50 ms, VCCIO */
static void r1_power_off(void)
{
	if (lcd_id) {
		hiby_lcd_spi_write9(CMD(0x28));
		mdelay(5);
		hiby_lcd_spi_write9(CMD(0x10));
	} else {
		spi_writecomm(0x2800);
		mdelay(5);
		spi_writecomm(0x1000);
	}
	mdelay(5);

	gpio_set_value(HIBY_LCD_RST, 0);
	hiby_lcd_supply(HIBY_LDO_VCC, 0);
	mdelay(50);
	hiby_lcd_supply(HIBY_LDO_VCCIO, 0);

	gpio_set_value(HIBY_LCD_SPI_MOSI, 0);
	gpio_set_value(HIBY_LCD_SPI_SCK, 0);
	gpio_set_value(HIBY_LCD_SPI_CS, 0);
}

/* lcd_lg35583.c: lcdc_data */
static struct hiby_panel r1_panel = {
	.refresh = 62,
	.xres = 480,
	.yres = 800,
	.left_margin = 24,
	.right_margin = 24,
	.upper_margin = 8,
	.lower_margin = 14,
	.hsync_len = 24,
	.vsync_len = 5,
	.color_even = 2,
	.color_odd = 2,
	.pins_off_first = 1,	/* firmware 2.0's soc_fb */
	.power_on = r1_power_on,
	.power_off = r1_power_off,
};

const struct hiby_panel *hiby_panel_probe(void)
{
	int mv = hiby_r1_adc_read_mv(LCD_ID_CHANNEL);

	lcd_id = mv >= LCD_ID_ST7701S_MV;
	r1_panel.name = lcd_id ? "ST7701S" : "LG35583";
	printf("display: panel ID %d mV: %s\n", mv, r1_panel.name);
	return &r1_panel;
}
