#define LG_ADDR_HI	0x2000
#define LG_ADDR_LO	0x0000
#define LG_DATA		0x4000

static void spi_writecomm(u16 reg)
{
	hiby_lcd_spi_write16(LG_ADDR_HI | (reg >> 8));
	hiby_lcd_spi_write16(LG_ADDR_LO | (reg & 0xff));
}

